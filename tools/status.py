#!/usr/bin/env python3
"""Generate repository status from analysis and authored records."""
import csv
import json
from pathlib import Path
from fetch_originals import ROOT, config

STAGES = ("located","named","typed","decompiled","compiles","matches","integrated")
def main():
    rows = list(csv.DictReader((ROOT/"records/functions.tsv").open(), delimiter="\t"))
    lines = ["# Status", "", "_Generated by tools/status.py. Do not edit._", "",
             "Header analysis is not function decompilation. Import slots are not unique imported functions.", "",
             "| Build | XEX import slots | Resources | .pdata functions | Distinct imports | Authored function records | Matches+ |",
             "|---|---:|---:|---:|---:|---:|---:|"]
    for b in config()["build"]:
        ident = b["id"]
        path = ROOT/"analysis"/ident/"xex.json"
        data = json.loads(path.read_text()) if path.is_file() else None
        own = [r for r in rows if r["build"] == ident]
        if any(r["status"] not in STAGES for r in own):
            raise ValueError("unknown status")
        matched = sum(STAGES.index(r["status"]) >= STAGES.index("matches") for r in own)
        imports = sum(x["slot_count"] for x in data["imports"]) if data else "pending"
        resources = len(data["resources"]) if data else "pending"
        decoded_path = ROOT/"analysis"/ident/"decoded.json"
        decoded = json.loads(decoded_path.read_text()) if decoded_path.is_file() else {}
        lines.append(f"| {ident} | {imports} | {resources} | {decoded.get('pdata_functions', 'pending')} | {decoded.get('distinct_imports', 'pending')} | {len(own)} | {matched} |")
    baseline = ROOT/"analysis"/"ghidra"/"xenon-12.2-validated.json"
    if baseline.is_file():
        g=json.loads(baseline.read_text())
        lines += ["", "## Ghidra Xenon analysis", "", f"Verified boundaries: {g['seeds_found']:,}/{g['seed_count']:,}; successful C exports: {g['decompile_success']:,}/{g['functions']:,}; unresolved heuristic candidates: {g['unresolved_candidates']:,}.", ""]
    lines += ["", "Native dashboard boot and full differential parity are not established. .pdata is a partial function inventory. Pseudocode exports are not authored reconstruction.", ""]
    (ROOT/"STATUS.md").write_text("\n".join(lines), encoding="utf-8")
if __name__ == "__main__":
    main()
